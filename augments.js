/* 단계별로 고를 수 있는 증강 */
export function poolFor(phase, mode) {
  const ok = a => (a.phase === 'any' || a.phase === phase);
  let pool = AUGMENTS.filter(ok);
  if (mode === 'simple') pool = pool.filter(a => SIMPLE_IDS.includes(a.id));
  return pool;
}
